/** One-time proof for the state-vocabulary migration; not a package build or runtime dependency. */
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { renameNodes } from './verifyStateVocabularySnapshots/utils/renameNodes.mjs';
import { sectionsOf } from './verifyStateVocabularySnapshots/utils/sectionsOf.mjs';

/** Fixture comparison is independent of the shipping node reader and retains schema/output keys. */
const renames = {
  active: 'isActive',
  visible: 'isVisible',
  disabled: 'isDisabled',
  readOnly: 'isReadOnly',
  required: 'isRequired',
  misfit: 'isMisfit',
  enabled: 'isPresent',
};
/** Repository root is resolved from this script so no machine path enters the proof. */
const root = fileURLToPath(new URL('../../../../../../..', import.meta.url));
/** Snapshot source shared by the stored histories and their producer. */
const directory = resolve(
  root,
  'packages/canard/schema-form/src/core/engine/settle/__tests__/fixtures/gate-table',
);
/** Explicit base commit, capture directory and optional controlled rewrite mode. */
const [base, captureDirectory, mode] = process.argv.slice(2);
assert(
  base && captureDirectory,
  'usage: node verifyStateVocabularySnapshots.mjs <base> <capture-directory> [--rewrite]',
);
/** All current snapshots, including load histories that reuse the same node observer. */
const fixtures = readdirSync(directory).filter((name) =>
  /^(selection|wheel|loading)-\d+\.json$/.test(name),
);
/** Pinned manifest used to independently verify the hashed large histories. */
const baselineManifest = JSON.parse(
  execFileSync(
    'git',
    [
      'show',
      `${base}:${relative(root, resolve(directory, 'large.manifest.json'))}`,
    ],
    { cwd: root, encoding: 'utf8' },
  ),
);
/** Regenerated hashes must describe the captured new-vocabulary sections with unchanged counts. */
const currentManifest = JSON.parse(
  readFileSync(resolve(directory, 'large.manifest.json'), 'utf8'),
);
assert.deepEqual(Object.keys(currentManifest), Object.keys(baselineManifest));

/** The required set is forty selection/wheel histories plus their hashed-section manifest. */
let required = 1;
for (const name of fixtures) {
  const file = resolve(directory, name);
  const before = JSON.parse(
    execFileSync('git', ['show', `${base}:${relative(root, file)}`], {
      cwd: root,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    }),
  );
  if (mode === '--rewrite') {
    if (before.observations)
      writeFileSync(file, JSON.stringify(renameNodes(before, renames)) + '\n');
    continue;
  }
  const current = JSON.parse(readFileSync(file, 'utf8'));
  if (before.observations)
    assert.equal(
      JSON.stringify(current),
      JSON.stringify(renameNodes(structuredClone(before), renames)),
      name + ': keys-only snapshot',
    );
  else
    assert.equal(
      JSON.stringify(current),
      JSON.stringify(before),
      name + ': retained sections must stay exact',
    );
  if (
    name === 'loading-12.json' &&
    !existsSync(resolve(captureDirectory, name))
  )
    continue;
  const captured = JSON.parse(
    readFileSync(resolve(captureDirectory, name), 'utf8'),
  );
  const capturedSections = before.observations
    ? undefined
    : sectionsOf(captured);
  renameNodes(
    captured,
    Object.fromEntries(
      Object.entries(renames).map(([old, next]) => [next, old]),
    ),
  );
  if (before.observations) {
    for (const history of [captured, before])
      for (const observation of history.observations) delete observation.latent;
    assert.equal(
      JSON.stringify(captured),
      JSON.stringify(before),
      name + ': inverse-renamed replay',
    );
  } else {
    const sections = sectionsOf(captured);
    for (const [key, record] of Object.entries(
      baselineManifest[name.slice(0, -5)],
    )) {
      const regenerated = currentManifest[name.slice(0, -5)][key];
      if (key === 'latent') {
        assert.deepEqual(
          regenerated,
          record,
          name + '/latent: ignored baseline is preserved',
        );
        continue;
      }
      const text = JSON.stringify(sections[key]);
      assert.equal(
        Buffer.byteLength(text),
        record.bytes,
        name + '/' + key + ': original bytes',
      );
      assert.equal(
        createHash('sha256').update(text).digest('hex'),
        record.sha256,
        name + '/' + key + ': original hash',
      );
      const currentText = JSON.stringify(capturedSections[key]);
      assert.equal(
        Buffer.byteLength(currentText),
        regenerated.bytes,
        name + '/' + key + ': regenerated bytes',
      );
      assert.equal(
        createHash('sha256').update(currentText).digest('hex'),
        regenerated.sha256,
        name + '/' + key + ': regenerated hash',
      );
      assert.deepEqual(
        regenerated.counts,
        record.counts,
        name + '/' + key + ': work counts',
      );
    }
  }
  if (/^(selection|wheel)-/.test(name)) required++;
}
if (mode !== '--rewrite') {
  assert.equal(required, 41);
  console.log(
    `STATE_VOCABULARY_SNAPSHOTS_OK required=${required} total=${fixtures.length}; inverse-renamed replay matches every baseline hash`,
  );
}
